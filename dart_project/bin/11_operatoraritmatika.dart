void main() {
  int a = 18;
  int b = 6;

  // Penjumlahan
  int sum = a + b;
  print('Penjumlahan: $a + $b = $sum');

  // Pengurangan
  int difference = a - b;
  print('Pengurangan: $a - $b = $difference');

  // Perkalian
  int product = a * b;
  print('Perkalian: $a * $b = $product');

  // Pembagian (hasilnya double)
  double quotient = a / b;
  print('Pembagian: $a / $b = $quotient');
}
